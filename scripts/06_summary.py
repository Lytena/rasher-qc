"""Step 6 - collect all result tables into one Markdown summary.

Every number quoted in the report is copied from results/<tag>/SUMMARY.md,
which this script generates from the JSON outputs of steps 1-5, so the report
and the code cannot drift apart.

Usage: python scripts/06_summary.py --data data/<dataset>
"""

from __future__ import annotations

from _common import METHOD_LABELS, load_json, out_dirs, parse

from rasherqc import config

a = parse(__doc__.split("\n")[0])
fig_dir, tab_dir, _ = out_dirs(a.tag)
J = lambda n: load_json(tab_dir / n) if (tab_dir / n).is_file() else None  # noqa: E731
st, ev, rb, pf, tr = J("data_stats.json"), J("evaluation.json"), J("robustness.json"), J("performance.json"), J("training.json")
L: list[str] = [f"# Results summary - `{a.tag}`\n", "_Generated by `scripts/06_summary.py`; do not edit by hand._\n"]
f = lambda v, d=3: "-" if v is None else (f"{v:.{d}f}" if isinstance(v, float) else str(v))  # noqa: E731
ci = lambda c: f"[{c[0]:.3f}, {c[1]:.3f}]"  # noqa: E731

if st:
    L.append("## Data\n\n| split | images | FAIL trays | " + " | ".join(next(iter(st.values()))["boxes"]) + " |")
    L.append("|---" * (3 + len(next(iter(st.values()))["boxes"])) + "|")
    for s, v in st.items():
        L.append(f"| {s} | {v['images']} | {v['fail_trays']} | " + " | ".join(str(n) for n in v["boxes"].values()) + " |")
    L.append("")

dv = J("dataset_variants.json")
if dv is None:  # variants are audited once, under the original dataset's tag
    base = config.RESULTS_DIR / a.tag.removesuffix("-reduced").removesuffix("-block") / "tables" / "dataset_variants.json"
    dv = load_json(base) if base.is_file() else None
if dv:
    g = dv["frame_gaps"]
    L.append("## Leakage audit of the predefined split\n")
    L.append("| split | median frames to nearest training frame | share <= 3 frames | share <= 30 frames | share same frame |\n|---|---|---|---|---|")
    for s_, v in g.items():
        L.append(f"| {s_} | {v['median']:.1f} | {v['frac_le_3']:.2f} | {v['frac_le_30']:.2f} | {v['frac_eq_0']:.2f} |")
    L.append(f"\nBlock split (block {dv['block_split']['block']} frames, guard {dv['block_split']['gap']} frames): "
             + ", ".join(f"{k} {v}" for k, v in dv["block_split"].items() if k in ("train", "valid", "test", "dropped_train_in_gap")) + "\n")

if ev:
    L.append("## Method comparison (test split; thresholds chosen on validation)\n")
    L.append("Tray = one image (frame). 'Evaluable' classes have >= 10 ground-truth boxes in the test split.\n")
    L.append("| method | mAP@0.5 (evaluable classes) | mAP@0.5:0.95 (evaluable) | mAP@0.5 (all classes with GT) | tray AUC [95% CI] | fail_conf | FAIL recall [95% CI] | false-reject [95% CI] | review band: escape / review rate |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for n, m in ev["methods"].items():
        t = m["tray"]
        c = t["test_at_fail_conf"]
        rbm = t["test_review_band"]
        mp = (f(m["test"].get("map50_evaluable")), f(m["test"].get("map50_95_evaluable")), f(m["test"]["map50"])) if "test" in m else ("n/a",) * 3
        L.append(f"| {METHOD_LABELS.get(n, n)} | {mp[0]} | {mp[1]} | {mp[2]} | {f(t['test_auc'])} {ci(t['test_ci95']['auc'])} | {f(t['fail_conf'], 4)} | "
                 f"{f(c['fail_recall'])} {ci(t['test_ci95']['fail_recall'])} | {f(c['false_reject_rate'])} {ci(t['test_ci95']['false_reject_rate'])} | "
                 f"{f(rbm['escape_rate'])} / {f(rbm['review_rate'])} |")
    L.append("")
    dets = [n for n, m in ev["methods"].items() if m["type"] == "detector"]
    if dets:
        L.append("### Detection AP@0.5 per class (test)\n")
        L.append("| class | GT boxes | " + " | ".join(METHOD_LABELS[n] for n in dets) + " |")
        L.append("|---|---|" + "---|" * len(dets))
        for k, c in enumerate(ev["classes"]):
            L.append(f"| {c} | {ev['methods'][dets[0]]['test']['n_gt'][k]} | " + " | ".join(f(ev['methods'][n]['test']['ap50'][k]) for n in dets) + " |")
        L.append("")
        L.append("### Metric verification: our mAP@0.5 vs Ultralytics validator (test)\n")
        L.append("| method | ours, COCO 101-pt | ours, trapezoid 101-pt (Ultralytics' rule) | Ultralytics |")
        L.append("|---|---|---|---|")
        for n in dets:
            u = ev["methods"][n].get("ultralytics_test", {})
            L.append(f"| {METHOD_LABELS[n]} | {f(ev['methods'][n]['test']['map50'], 4)} | {f(ev['methods'][n]['test']['map50_trapz101'], 4)} | {f(u.get('map50'), 4)} |")
        L.append("")
    L.append("### Per-class presence AUC (is defect type X on the tray?), test\n")
    L.append("| class | " + " | ".join(METHOD_LABELS[n] for n in ev["methods"]) + " |")
    L.append("|---|" + "---|" * len(ev["methods"]))
    for c in ev["classes"]:
        L.append(f"| {c} | " + " | ".join(f(ev['methods'][n]['presence_auc_test'][c]) for n in ev["methods"]) + " |")
    L.append("")
    if "recall_vs_size" in ev:
        L.append("### Detection recall vs defect size (test, at fail_conf, IoU >= 0.5)\n")
        for n, v in ev["recall_vs_size"].items():
            b = v["bins"]
            L.append(f"**{METHOD_LABELS[n]}**: " + ", ".join(
                f"{b[i]*100:.1f}-{b[i+1]*100:.1f}%: {v['recall'][i]:.2f} (n={int(v['n'][i])})" for i in range(len(b) - 1)))
            L.append("")
    rbm = ev["methods"].get("rf_baseline")
    if rbm:
        L.append(f"Baseline CV (5-fold, train split) best ROC-AUC = {rbm['cv']['best_score']:.3f} with {rbm['cv']['best_params']}; "
                 f"feature extraction {rbm['feature_time_s']:.0f} s for all splits, fit {rbm['fit_time_s']:.0f} s.\n")
        L.append("Top features: " + ", ".join(f"{n} ({v:.3f})" for n, v in rbm["top_features"][:8]) + "\n")

if tr:
    L.append("## Training\n\n| model | epochs run | wall time (min) | device | imgsz |\n|---|---|---|---|---|")
    for n, v in tr.items():
        L.append(f"| {METHOD_LABELS.get(n, n)} | {v['epochs_run']} | {v['wall_time_s']/60:.1f} | {v['device']} | {v['imgsz']} |")
    L.append("")

if rb:
    L.append("## Robustness (test; FAIL recall / false-reject at fixed thresholds)\n")
    for n, sweeps in rb.items():
        L.append(f"**{METHOD_LABELS.get(n, n)}**\n\n| perturbation | " + " | ".join("level" for _ in range(1)) + " -> recall / false-reject (mAP@0.5) |\n|---|---|")
        for s, rows in sweeps.items():
            cells = "; ".join(f"{r['level']}: {r['fail_recall']:.2f}/{r['false_reject_rate']:.2f}" + (f" ({r['map50']:.2f})" if r["map50"] is not None else "") for r in rows)
            L.append(f"| {s} | {cells} |")
        L.append("")

if pf:
    h = pf["hardware"]
    mach = h.get("machine", {})
    L.append(f"## Performance ({mach.get('gpu') or 'CPU'}; {mach.get('processor') or ''}, {mach.get('cpu_count') or h['torch_threads']} logical CPUs)\n")
    L.append(f"Measured attainable compute {h['peak_gflops']:.1f} GFLOP/s, memory bandwidth {h['bandwidth_gbs']:.1f} GB/s "
             f"-> ridge point {h['peak_gflops']/h['bandwidth_gbs']:.1f} FLOP/byte. Line-rate budget {pf['budget_ms']:.0f} ms/tray "
             f"({pf['line_rate_trays_per_min']:.0f} trays/min).\n")
    if "detector" in pf:
        d = pf["detector"]
        L.append(f"YOLOv8n: {d['params']/1e6:.2f} M parameters, {d['weights_mb']:.1f} MB weights, {d['n_conv_layers']} conv layers; "
                 f"input {d['input_hw'][1]}x{d['input_hw'][0]}: {d['conv_gflops_ours']:.2f} GFLOPs (our counter) vs "
                 f"{f(d['gflops_thop'], 2) if isinstance(d['gflops_thop'], float) else d['gflops_thop']} GFLOPs (thop); "
                 f"arithmetic intensity whole-network {d['ai_total']:.1f} FLOP/byte (layers {d['ai_min']:.1f}-{d['ai_max']:.1f}); "
                 f"largest activation {d['largest_activation_mb']:.1f} MB; peak process RSS {d['peak_rss_mb']:.0f} MB.\n")
        L.append("| imgsz | latency mean (ms) | p95 (ms) | inference (ms) | NMS (ms) | GFLOPs | attained GFLOP/s | mAP@0.5 | FAIL recall | false-reject |")
        L.append("|---|---|---|---|---|---|---|---|---|---|")
        for s, v in sorted(pf["detector_sizes"].items(), key=lambda kv: int(kv[0])):
            lt = v["latency"]
            L.append(f"| {s} | {lt['mean_ms']:.1f} | {lt['p95_ms']:.1f} | {lt['inf_ms']:.1f} | {lt['post_ms']:.1f} | {v['conv_gflops']:.2f} | "
                     f"{v['attained_gflops']:.1f} | {v['map50']:.3f} | {v['fail_recall']:.3f} | {v['false_reject_rate']:.3f} |")
        L.append("")
        if "cpu_latency_by_imgsz" in d:
            L.append("CPU latency on the same machine (ms, mean / p95): " + ", ".join(
                f"{k}px {v['mean_ms']:.1f} / {v['p95_ms']:.1f}" for k, v in d["cpu_latency_by_imgsz"].items()) + "\n")
        L.append("Throughput vs batch (img/s): " + ", ".join(f"batch {k}: {v:.1f}" for k, v in d["throughput_img_per_s_by_batch"].items()))
        L.append("; inference ms vs threads: " + ", ".join(f"{k} thread(s): {v:.1f}" for k, v in d["inference_ms_by_threads"].items()) + "\n")
    b = pf["baseline"]
    if "detector" in pf and "cpu_attained_gflops" in pf["detector"]:
        L.append(f"CPU roofline position at {config.DEFAULT_IMGSZ}px: attained {pf['detector']['cpu_attained_gflops']:.1f} GFLOP/s "
                 f"({pf['detector']['cpu_attained_gflops']/h['peak_gflops']*100:.0f} % of measured peak), inference {pf['detector']['cpu_inf_ms_default']:.1f} ms.\n")
    if "bandwidth_numpy_1thread_gbs" in h:
        L.append(f"Bandwidth: NumPy single-thread copy {h['bandwidth_numpy_1thread_gbs']:.1f} GB/s, PyTorch multi-thread copy {h['bandwidth_torch_multithread_gbs']:.1f} GB/s.\n")
    if b.get("parallel_actually_used") is False:
        L.append("Note: on this OS the 2-process feature extraction falls back to serial; the 'parallel' timing is a second serial run.\n")
    L.append(f"Baseline features: reference {b['reference']['ms_per_image']:.1f} ms/img -> optimised {b['fast']['ms_per_image']:.1f} ms/img "
             f"({b['reference']['ms_per_image']/b['fast']['ms_per_image']:.2f}x); 2 processes {b['parallel2_ms_per_image']:.1f} ms/img "
             f"vs serial {b['serial_ms_per_image']:.1f}; end-to-end {f(b.get('end_to_end_ms'), 1)} ms/tray; RF predict {f(b.get('rf_predict_ms'), 2)} ms.\n")
    L.append("Profile (ms/img, cumulative): reference " + ", ".join(f"{k} {v:.1f}" for k, v in sorted(b["reference"]["profile_ms"].items(), key=lambda kv: -kv[1]))
             + "; optimised " + ", ".join(f"{k} {v:.1f}" for k, v in sorted(b["fast"]["profile_ms"].items(), key=lambda kv: -kv[1])) + "\n")

(config.RESULTS_DIR / a.tag / "SUMMARY.md").write_text("\n".join(L))
print("\n".join(L))
